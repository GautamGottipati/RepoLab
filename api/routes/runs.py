"""The Spark playground: running the pipeline and reading its measurements.

A run is ten to fifteen seconds of real Spark in a container, so ``POST /runs``
creates a job, enqueues it and returns immediately. Progress arrives on the job's
existing event stream, and the measurements arrive here once the run is done.

Every figure these endpoints return was computed by Python from the event log
Spark wrote. Nothing here consults a model, and nothing is estimated.
"""

from __future__ import annotations

from typing import Annotated, Any

import structlog
from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from api.deps import get_session
from repolab.db.jobs import create_job
from repolab.db.models import SparkRun
from repolab.db.runs import load_run_for_job, load_spark_run, load_spark_runs
from repolab.events import JobStatus
from repolab.experiences.spark.dataset import DEFAULT_ROWS, DEFAULT_SEED, generate_dataset
from repolab.experiences.spark.driver import ADDED_STEPS, DEFAULT_SHUFFLE_PARTITIONS
from repolab.ingest.url import InvalidRepoUrlError, validate_repo_url

log = structlog.get_logger(__name__)

router = APIRouter(tags=["playground"])

#: Bounds on what the playground may be asked to run.
#:
#: The same allowlisted range the experiment validator uses for this setting, so
#: a value typed into the playground and a value proposed by a model are held to
#: one standard.
MIN_PARTITIONS = 1
MAX_PARTITIONS = 2000

#: Dataset bounds. The lower bound keeps the skew visible; the upper bound keeps
#: a browser-initiated run from becoming an unbounded compute request.
MIN_ROWS = 1_000
MAX_ROWS = 2_000_000

#: Rows returned by the dataset preview.
PREVIEW_ROWS = 8


class StartRun(BaseModel):
    """A pipeline run to execute."""

    repo_url: str = Field(description="Public https repository URL")
    shuffle_partitions: int = Field(
        default=DEFAULT_SHUFFLE_PARTITIONS, ge=MIN_PARTITIONS, le=MAX_PARTITIONS
    )
    rows: int | None = Field(default=None, ge=MIN_ROWS, le=MAX_ROWS)


class RunStarted(BaseModel):
    job_id: str
    status: JobStatus
    repo_url: str
    shuffle_partitions: int
    events_url: str
    run_url: str


class RunView(BaseModel):
    """One measured run, as the playground renders it."""

    run_id: str
    job_id: str | None
    repo_url: str
    commit_sha: str
    dataset_hash: str

    configuration: dict[str, Any] | None = None
    environment: dict[str, Any] | None = None
    dataset: dict[str, Any] | None = None
    measurements: dict[str, Any] | None = None
    evidence: dict[str, Any] | None = None

    task_count: int
    stage_count: int
    total_runtime_ms: int | None
    wall_clock_seconds: float

    event_log_sha256: str
    event_log_bytes: int
    added_steps: list[str] = Field(default_factory=lambda: list(ADDED_STEPS))
    """What RepoLab adds to the repository's own job, disclosed with every run."""


class DatasetPreview(BaseModel):
    """The input data panel: what the pipeline will read.

    The preview is cut from the *real* generated bytes, so the hash shown here is
    the hash the run will record. A sample invented for display would be the one
    thing on this screen that was not evidence.
    """

    spec: dict[str, Any]
    columns: list[str]
    header: str
    rows: list[list[str]]
    preview_rows: int
    total_rows: int
    distinct_keys: int
    """Computed from the generator, not assumed by the caller.

    ``DatasetSpec`` exposes this as a property, which pydantic does not
    serialise, so without it here a screen would have to hardcode the number --
    and an unevidenced figure is exactly what this product must not show.
    """

    sha256: str


def _view(record: SparkRun) -> RunView:
    return RunView(
        run_id=record.run_id,
        job_id=record.job_id,
        repo_url=record.repo_url,
        commit_sha=record.commit_sha,
        dataset_hash=record.dataset_hash,
        configuration=record.configuration,
        environment=record.environment,
        dataset=record.dataset,
        measurements=record.measurements,
        evidence=record.evidence,
        task_count=record.task_count,
        stage_count=record.stage_count,
        total_runtime_ms=record.total_runtime_ms,
        wall_clock_seconds=record.wall_clock_seconds,
        event_log_sha256=record.event_log_sha256,
        event_log_bytes=record.event_log_bytes,
    )


@router.post("/runs", response_model=RunStarted, status_code=status.HTTP_202_ACCEPTED)
def start_run(
    payload: StartRun,
    response: Response,
    session: Annotated[Session, Depends(get_session)],
) -> RunStarted:
    """Run the repository's pipeline on real Spark. Returns 202; it runs in a worker."""
    try:
        repo_url = validate_repo_url(payload.repo_url)
    except InvalidRepoUrlError as exc:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, str(exc)) from exc

    job = create_job(session, repo_url.normalized, kind="spark_run")
    session.commit()

    try:
        from worker.jobs import enqueue_spark_run

        enqueue_spark_run(
            job.id,
            repo_url.normalized,
            shuffle_partitions=payload.shuffle_partitions,
            rows=payload.rows,
        )
    except Exception as exc:  # noqa: BLE001 - reported; the job row survives
        log.warning("runs.enqueue_failed", job_id=job.id, error=str(exc))

    response.headers["Location"] = f"/jobs/{job.id}/run"
    return RunStarted(
        job_id=job.id,
        status=JobStatus.QUEUED,
        repo_url=repo_url.normalized,
        shuffle_partitions=payload.shuffle_partitions,
        events_url=f"/jobs/{job.id}/events",
        run_url=f"/jobs/{job.id}/run",
    )


@router.get("/runs", response_model=list[RunView])
def index(
    session: Annotated[Session, Depends(get_session)],
    repo_url: Annotated[str, Query(description="Repository to list runs for")],
    limit: Annotated[int, Query(ge=1, le=100)] = 20,
) -> list[RunView]:
    """Measured runs for a repository, newest first."""
    return [_view(record) for record in load_spark_runs(session, repo_url)[:limit]]


@router.get("/runs/dataset", response_model=DatasetPreview)
def dataset_preview(
    rows: Annotated[int, Query(ge=MIN_ROWS, le=MAX_ROWS)] = DEFAULT_ROWS,
    seed: Annotated[int, Query()] = DEFAULT_SEED,
) -> DatasetPreview:
    """The deterministic dataset the pipeline reads, and its first rows."""
    data, spec = generate_dataset(rows=rows, seed=seed)

    lines = data.decode().splitlines()
    header = lines[0] if lines else ""
    sample = [line.split(",") for line in lines[1 : PREVIEW_ROWS + 1]]

    return DatasetPreview(
        spec=spec.model_dump(mode="json"),
        columns=header.split(",") if header else [],
        header=header,
        rows=sample,
        preview_rows=len(sample),
        total_rows=spec.rows,
        distinct_keys=spec.distinct_keys,
        sha256=spec.sha256,
    )


@router.get("/runs/{run_id}", response_model=RunView)
def run(run_id: str, session: Annotated[Session, Depends(get_session)]) -> RunView:
    """One measured run."""
    record = load_spark_run(session, run_id)
    if record is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, f"no run {run_id}")
    return _view(record)


@router.get("/jobs/{job_id}/run", response_model=RunView)
def run_for_job(job_id: str, session: Annotated[Session, Depends(get_session)]) -> RunView:
    """The run a job produced. 404 until it has finished measuring one."""
    from repolab.db.jobs import get_job

    if get_job(session, job_id) is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, f"no job {job_id}")

    record = load_run_for_job(session, job_id)
    if record is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, f"job {job_id} has not produced a run yet")
    return _view(record)
