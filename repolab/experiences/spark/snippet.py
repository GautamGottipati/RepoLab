"""Running a learner's own PySpark against a small dataset, and measuring it.

The Spark experience's unit of work: a few lines of DataFrame code, run by
``spark-submit`` inside a fresh, network-less container, against a deterministic
sample dataset. What comes back is real:

    output        the rows ``result`` holds, collected by Spark
    measurements  jobs, stages, tasks, partitions and runtime, parsed from the
                  event log Spark itself wrote (the same parser the experiments use)
    plan          Spark's own ``explain`` of the physical plan

The driver around the learner's code is RepoLab's and is disclosed. A run that
fails says why in Spark's or Python's own words; nothing is filled in.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import random
import shutil
import time
import uuid
from pathlib import Path

from pydantic import BaseModel, Field

from repolab.experiences.spark.eventlog import find_event_log, parse_event_log
from repolab.experiences.spark.measurements import SparkRunMeasurements, measure

WORKDIR = "/work"
DATASET_PATH = f"{WORKDIR}/sales.csv"
DRIVER_PATH = f"{WORKDIR}/repolab_experience.py"
EVENT_LOG_DIR = f"{WORKDIR}/events"

SUCCESS = "REPOLAB_EXPERIENCE_OK"
RESULT = "REPOLAB_EXPERIENCE_RESULT"
PLAN = "REPOLAB_EXPERIENCE_PLAN"
FAILED = "REPOLAB_EXPERIENCE_FAILED"

#: Rows of output kept; a learner reads a table, not a dump.
MAX_ROWS = 50
RUN_TIMEOUT = 300.0

COUNTRIES = ("US", "India", "Germany", "Brazil", "Japan", "Kenya")
CATEGORIES = ("books", "games", "garden", "music", "tools")
NAMES = ("Alice", "Bob", "Carol", "Dev", "Eve", "Femi", "Grace", "Hiro", "Ines", "Juan")


class SampleDataset(BaseModel):
    name: str = "sales.csv"
    rows: int
    columns: list[tuple[str, str]]
    preview: list[list[str]]
    sha256: str
    seed: int
    generated_by: str = "RepoLab (deterministic, seeded)"


def sample_dataset(*, rows: int = 2000, seed: int = 7) -> tuple[bytes, SampleDataset]:
    """A small sales table, byte-identical for the same seed."""
    rng = random.Random(seed)
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    header = ["order_id", "customer", "age", "country", "category", "amount"]
    writer.writerow(header)
    preview: list[list[str]] = []
    for order in range(1, rows + 1):
        row = [
            str(order),
            rng.choice(NAMES),
            str(rng.randint(14, 80)),
            # US-heavy on purpose, so a shuffle has an uneven key to show.
            "US" if rng.random() < 0.4 else rng.choice(COUNTRIES[1:]),
            rng.choice(CATEGORIES),
            str(rng.randint(5, 400)),
        ]
        writer.writerow(row)
        if len(preview) < 8:
            preview.append(row)
    data = buffer.getvalue().encode()
    return data, SampleDataset(
        rows=rows,
        columns=[
            ("order_id", "INT"),
            ("customer", "STRING"),
            ("age", "INT"),
            ("country", "STRING"),
            ("category", "STRING"),
            ("amount", "INT"),
        ],
        preview=preview,
        sha256=hashlib.sha256(data).hexdigest(),
        seed=seed,
    )


DRIVER = '''\
"""RepoLab experience driver. It loads the sample data, runs your code, and
reports what Spark returned. Generated by RepoLab."""
import json, sys, traceback
from pyspark.sql import SparkSession, functions as F

spark = SparkSession.builder.getOrCreate()
schema = "order_id INT, customer STRING, age INT, country STRING, category STRING, amount INT"
df = spark.read.csv({dataset!r}, header=True, schema=schema)
namespace = {{"spark": spark, "df": df, "F": F}}
try:
    exec(compile({code!r}, "<your code>", "exec"), namespace)
except Exception:
    print({failed!r}, json.dumps(traceback.format_exc()[-4000:]))
    spark.stop()
    raise SystemExit(4)

result = namespace.get("result")
if hasattr(result, "collect") and hasattr(result, "columns"):
    try:
        plan = result._jdf.queryExecution().executedPlan().toString()
        print({plan!r}, json.dumps(plan[:6000]))
    except Exception:
        pass
    def cell(v):
        return v if v is None or isinstance(v, (int, float, str, bool)) else str(v)
    rows = [[cell(v) for v in r] for r in result.limit({max_rows}).collect()]
    print({result_marker!r}, json.dumps({{"columns": result.columns, "rows": rows}}))
elif result is not None:
    plain = isinstance(result, (int, float, str, bool))
    print({result_marker!r}, json.dumps({{"value": result if plain else str(result)}}))
else:
    print({result_marker!r}, json.dumps({{"value": None}}))
print({success!r}, spark.version)
spark.stop()
'''


def render_driver(code: str) -> str:
    return DRIVER.format(
        dataset=DATASET_PATH,
        code=code,
        failed=FAILED,
        plan=PLAN,
        result_marker=RESULT,
        success=SUCCESS,
        max_rows=MAX_ROWS,
    )


class SnippetConfig(BaseModel):
    shuffle_partitions: int = 4
    master: str = "local[4]"
    driver_memory: str = "1g"

    def submit_args(self) -> list[str]:
        conf = {
            "spark.sql.shuffle.partitions": str(self.shuffle_partitions),
            "spark.eventLog.enabled": "true",
            "spark.eventLog.dir": f"file://{EVENT_LOG_DIR}",
            "spark.ui.enabled": "false",
            # So the partition count a learner sets is the one that runs.
            "spark.sql.adaptive.enabled": "false",
            "spark.driver.memory": self.driver_memory,
        }
        args = ["--master", self.master, "--name", "repolab-experience"]
        for key, value in conf.items():
            args += ["--conf", f"{key}={value}"]
        return args


class SnippetRunResult(BaseModel):
    run_id: str
    ok: bool
    code: str
    config: SnippetConfig
    image: str
    spark_version: str | None = None
    columns: list[str] = Field(default_factory=list)
    rows: list[list[object]] = Field(default_factory=list)
    value: object | None = None
    error: str | None = None
    plan: str | None = None
    measurements: SparkRunMeasurements | None = None
    jobs: int = 0
    event_log_sha256: str | None = None
    event_log_path: str | None = None
    dataset_sha256: str
    wall_clock_seconds: float = 0.0
    stdout_tail: str = ""


def parse_output(stdout: str) -> dict[str, object]:
    """The markers the driver printed, decoded."""
    found: dict[str, object] = {}
    for line in stdout.splitlines():
        for marker in (RESULT, PLAN, FAILED):
            if line.startswith(marker + " "):
                try:
                    found[marker] = json.loads(line[len(marker) + 1 :])
                except json.JSONDecodeError:
                    found[marker] = line[len(marker) + 1 :]
        if line.startswith(SUCCESS + " "):
            found[SUCCESS] = line[len(SUCCESS) + 1 :].strip()
    return found


def count_jobs(event_log: Path) -> int:
    return sum(
        1
        for line in event_log.read_text(errors="replace").splitlines()
        if '"Event":"SparkListenerJobStart"' in line
    )


class SnippetRunner:
    """One run, in an environment the caller provides and this runner stops."""

    def __init__(self, environment, *, runs_root: Path | None = None) -> None:
        self._environment = environment
        self._runs_root = runs_root or Path(".repolab/experience-runs")

    async def run(
        self,
        *,
        image: str,
        code: str,
        spark_submit: str,
        config: SnippetConfig | None = None,
        workdir: str | None = None,
        env: dict[str, str] | None = None,
    ) -> SnippetRunResult:
        config = config or SnippetConfig()
        run_id = uuid.uuid4().hex[:12]
        data, dataset = sample_dataset()
        started = time.perf_counter()
        await self._environment.start(image)
        try:
            await self._environment.run(f"mkdir -p {EVENT_LOG_DIR}")
            await self._environment.put_files(
                {DATASET_PATH: data, DRIVER_PATH: render_driver(code).encode()}
            )
            command = f"{spark_submit} {' '.join(config.submit_args())} {DRIVER_PATH}"
            # Without a network Spark cannot resolve the container's own address;
            # it binds to loopback instead, which is all a local[*] master needs.
            run_env = {"SPARK_LOCAL_IP": "127.0.0.1", "SPARK_LOCAL_HOSTNAME": "localhost"}
            run_env.update(env or {})
            result = await self._environment.run(
                command, timeout=RUN_TIMEOUT, cwd=workdir, env=run_env
            )
            stdout, stderr = result.stdout or "", result.stderr or ""
            markers = parse_output(stdout)
            outcome = SnippetRunResult(
                run_id=run_id,
                ok=SUCCESS in markers and result.exit_code == 0,
                code=code,
                config=config,
                image=image,
                dataset_sha256=dataset.sha256,
                stdout_tail=(stdout + "\n" + stderr)[-4000:],
            )
            if FAILED in markers:
                outcome.error = str(markers[FAILED])
            elif not outcome.ok:
                tail = (stderr or stdout).strip().splitlines()[-15:]
                outcome.error = "\n".join(tail) or f"spark-submit exited {result.exit_code}"
            payload = markers.get(RESULT)
            if isinstance(payload, dict):
                outcome.columns = list(payload.get("columns") or [])
                outcome.rows = list(payload.get("rows") or [])
                outcome.value = payload.get("value")
            if isinstance(markers.get(PLAN), str):
                outcome.plan = str(markers[PLAN])
            if isinstance(markers.get(SUCCESS), str):
                outcome.spark_version = str(markers[SUCCESS])

            host = getattr(self._environment, "host_workdir", None)
            found = find_event_log(Path(host) / "events") if host else None
            if found is not None:
                destination = self._runs_root / run_id
                destination.mkdir(parents=True, exist_ok=True)
                preserved = destination / found.name
                shutil.copy2(found, preserved)
                parsed = parse_event_log(preserved)
                outcome.measurements = measure(parsed)
                outcome.spark_version = outcome.spark_version or parsed.spark_version
                outcome.jobs = count_jobs(preserved)
                raw = preserved.read_bytes()
                outcome.event_log_sha256 = hashlib.sha256(raw).hexdigest()
                outcome.event_log_path = str(preserved)
            outcome.wall_clock_seconds = round(time.perf_counter() - started, 3)
            return outcome
        finally:
            await self._environment.stop()
