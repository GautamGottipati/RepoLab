"""An experiment on what a learner ran: the same code, one setting varied.

Implements the experiment executor's :class:`VariantRunner` so the existing loop
-- approval, repeats, the equivalence check, deterministic statistics, grounded
explanation -- runs a learner's own snippet on their session's runtime instead of
a repository's job. Each variant is a fresh, network-less container from the
same image, on the same seeded dataset; only ``spark.sql.shuffle.partitions``
changes.
"""

from __future__ import annotations

from collections.abc import Callable

from repolab.evidence.models import EvidenceBundle
from repolab.experiences.spark.dataset import DatasetSpec
from repolab.experiences.spark.driver import SparkRunConfig
from repolab.experiences.spark.runner import (
    RunEnvironmentInfo,
    SparkRunFailed,
    SparkRunResult,
)
from repolab.experiences.spark.snippet import SnippetConfig, SnippetRunner, sample_dataset

VARIABLE = "spark.sql.shuffle.partitions"


class SnippetVariantRunner:
    def __init__(
        self,
        *,
        repo_url: str,
        commit_sha: str,
        image: str,
        spark_submit: str,
        code: str,
        environment_factory: Callable[[], object] | None = None,
    ) -> None:
        self._repo_url = repo_url
        self._commit_sha = commit_sha
        self._image = image
        self._spark_submit = spark_submit
        self._code = code
        self._environment_factory = environment_factory

    @property
    def image(self) -> str:
        return self._image

    def _environment(self) -> object:
        if self._environment_factory is not None:
            return self._environment_factory()
        from repolab.sandbox.docker import DockerEnvironment

        return DockerEnvironment(hardened=True)

    async def run_once(self, *, value: int, repeat: int) -> SparkRunResult:
        result = await SnippetRunner(self._environment()).run(
            image=self._image,
            code=self._code,
            spark_submit=self._spark_submit,
            config=SnippetConfig(shuffle_partitions=value),
        )
        if not result.ok or result.measurements is None or result.event_log_path is None:
            raise SparkRunFailed(result.error or "the run produced no event log")
        data, sample = sample_dataset()
        dataset = DatasetSpec(
            rows=sample.rows,
            seed=sample.seed,
            columns=[name for name, _ in sample.columns],
            skewed_key="US",
            skew_fraction=0.4,
            skewed_rows=data.count(b",US,"),
            sha256=sample.sha256,
            size_bytes=len(data),
            filename=sample.name,
        )
        run = SparkRunResult(
            run_id=result.run_id,
            repo_url=self._repo_url,
            commit_sha=self._commit_sha,
            dataset=dataset,
            config=SparkRunConfig(shuffle_partitions=value, app_name="repolab-experience"),
            environment=RunEnvironmentInfo(
                kind="docker",
                image=self._image,
                spark_version=result.spark_version,
                master=SnippetConfig().master,
            ),
            measurements=result.measurements,
            evidence=EvidenceBundle(),
            event_log_path=result.event_log_path,
            event_log_sha256=result.event_log_sha256 or "",
            event_log_bytes=0,
            driver_stdout_tail=result.stdout_tail,
            added_steps=[
                "the learner's own code from their experience session, run as written",
                "a seeded sample dataset generated by RepoLab (sales.csv)",
            ],
            wall_clock_seconds=result.wall_clock_seconds,
        )
        run.evidence = EvidenceBundle(measurements=result.measurements.to_measurements())
        return run
