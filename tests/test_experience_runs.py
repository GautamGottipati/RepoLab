"""Running an experience: what comes back is real, and labelled for what it is.

Offline. A fake environment stands in for the container: it records how it was
started and replays a *real* Spark event log (tests/fixtures/spark) as what the
run wrote. Covered:

* the driver around learner code, and parsing what it printed;
* measurements come only from the event log; a failed run carries Spark's error;
* "what just happened" links only to parts the architecture graph has;
* an experiment can run the learner's snippet through the existing executor;
* explanations are verified (measured claims need recorded measurements);
* user code runs hardened: no network, no capabilities;
* the API: start, reconnect, run, Mini Lab, and the experiment target.
"""

