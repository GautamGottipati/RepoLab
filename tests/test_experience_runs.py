class TestWhatHappened:
    RESULT: ClassVar[dict] = {
        "ok": True,
        "jobs": 1,
        "columns": ["country"],
        "rows": [["US"], ["India"]],
        "plan": "*(2) HashAggregate(keys=[c])\n+- Exchange hashpartitioning(c, 4)",
        "measurements": {"stage_count": 2, "task_count": 5, "total_runtime_ms": 900},
    }

    def test_each_step_needs_run_evidence_and_links_only_to_real_parts(self) -> None:
        steps = map_run(self.RESULT, GRAPH)
        titles = [s.title for s in steps]
        assert titles[0] == "Your code" and titles[-1] == "Result"
        planning = next(s for s in steps if s.title == "Query planning")
        assert "Exchange is a shuffle" in planning.run_evidence
        assert planning.architecture_id == "concept:catalyst"
        scheduler = next(s for s in steps if s.title == "Scheduler")
        assert scheduler.run_evidence == "1 job split into 2 stages"
        assert scheduler.architecture_id == "concept:scheduler" and scheduler.source_paths == [
            "core"
        ]
        assert (
            next(s for s in steps if s.title == "Result").run_evidence
            == "2 rows came back to the driver"
        )

    def test_without_a_graph_nothing_is_linked(self) -> None:
        assert all(s.architecture_id is None for s in map_run(self.RESULT, None))

    def test_a_failed_run_maps_nothing(self) -> None:
        assert map_run({**self.RESULT, "ok": False}, GRAPH) == []

    def test_plan_operators_skip_expression_keywords(self) -> None:
        plan = "Sort [x DESC NULLS LAST]\n+- Filter (a AND b)\n+- FileScan csv"
        assert plan_operators(plan) == ["Sort", "Filter", "FileScan"]

    def test_measurements_are_the_runs_own(self) -> None:
        names = {m.name: m.value for m in run_measurements(self.RESULT)}
        assert names["jobs"] == 1 and names["stages"] == 2 and names["tasks"] == 5
        assert names["total runtime ms"] == 900


class TestAnExperimentOnTheLearnersCode:
    def test_each_variant_is_a_fresh_run_with_only_partitions_changed(self, tmp_path: Path) -> None:
        made: list[FakeEnvironment] = []

        def factory() -> FakeEnvironment:
            env = FakeEnvironment(
                tmp_path / f"w{len(made)}", stdout=printed(result={"columns": [], "rows": []})
            )
            made.append(env)
            return env

        runner = SnippetVariantRunner(
            repo_url="https://github.com/apache/spark",
            commit_sha="c" * 40,
            image="spark:test",
            spark_submit="/opt/spark/bin/spark-submit",
            code="result = df",
            environment_factory=factory,
        )
        first = asyncio.run(runner.run_once(value=2, repeat=0))
        second = asyncio.run(runner.run_once(value=8, repeat=0))
        assert len(made) == 2 and all(env.stopped for env in made)
        assert first.config.shuffle_partitions == 2 and second.config.shuffle_partitions == 8
        assert first.dataset.sha256 == second.dataset.sha256  # equivalent state
        assert "spark.sql.shuffle.partitions=8" in made[1].commands[-1][0]
        assert first.evidence.measurements and first.environment.image == "spark:test"

    def test_a_failed_variant_raises_rather_than_measuring_nothing(self, tmp_path: Path) -> None:
        from repolab.experiences.spark.runner import SparkRunFailed

        runner = SnippetVariantRunner(
            repo_url="r",
            commit_sha="c",
            image="i",
            spark_submit="s",
            code="x",
            environment_factory=lambda: FakeEnvironment(tmp_path, stdout="", write_log=False),
        )
        with pytest.raises(SparkRunFailed):
            asyncio.run(runner.run_once(value=4, repeat=0))


class TestIsolation:
    def test_learner_code_runs_without_network_or_capabilities(self, tmp_path: Path) -> None:
        argv = build_run_command("img", "c1", tmp_path, hardened=True)
        joined = " ".join(argv)
        assert "--network none" in joined
        assert "--cap-drop ALL" in joined
        assert "--pids-limit" in joined and "no-new-privileges" in joined
        assert set(HARDENED_FLAGS) <= set(argv)

    def test_the_spark_demo_runs_as_before(self, tmp_path: Path) -> None:
        assert "--network" not in build_run_command("img", "c1", tmp_path)

    def test_library_snippets_run_with_a_timeout_and_bounded_output(self, tmp_path: Path) -> None:
        environment = FakeEnvironment(tmp_path, stdout="x" * 30_000, write_log=False)
        result = asyncio.run(run_snippet(environment, image="lib:test", code="print(1)"))
        assert result.ok and result.truncated and len(result.stdout) == 20_000
        assert environment.files["/work/snippet.py"] == b"print(1)"
        assert environment.stopped


class TestExplaining:
    def test_explanations_are_verified_against_the_runs_measurements(self) -> None:
        from repolab.experiences.explain import evidence_for, explain_run
        from repolab.questions.models import AnswerClaim, AnswerClaimKind, GroundedAnswer

        produced = GroundedAnswer(
            answer="It shuffled.",
            summary="Spark ran 1 job.",
            claims=[
                AnswerClaim(
                    kind=AnswerClaimKind.MEASURED, statement="One job ran.", support="jobs"
                ),
                AnswerClaim(
                    kind=AnswerClaimKind.MEASURED, statement="It used 9 GB.", support="memory"
                ),
            ],
            caveats=[],
        )

        class Router:
            prompt = ""

            async def super(self, **kw):
                Router.prompt = kw["prompt"]

                class Completion:
                    value = produced

                return Completion()

        evidence = evidence_for(run_measurements(TestWhatHappened.RESULT), [], "")
        verified = asyncio.run(
            explain_run(
                router=Router(),
                code="result = df",
                result=TestWhatHappened.RESULT,
                mapping=[],
                measurements=evidence,
                runtime_label="Official Apache Spark 3.5.1",
            )
        )
        assert [u.statement for u in verified.unsupported] == ["It used 9 GB."]
        assert "Official Apache Spark 3.5.1" in Router.prompt
        assert "- jobs: 1 count" in Router.prompt


class TestTheSourceBuildPreflight:
    def test_a_build_that_cannot_fit_is_refused_before_it_starts(self, monkeypatch) -> None:
        import subprocess

        from repolab.experiences.facts import SparkRuntimeFacts
        from worker.experience_tasks import BUILD_OVERHEAD_GB, _container_memory, _memory_check

        class Info:
            stdout = str(int(7.66 * 1024**3))

        monkeypatch.setattr(subprocess, "run", lambda *a, **k: Info())
        facts = SparkRuntimeFacts(spark_submit="bin/spark-submit", compiler_heap_gb=4)
        needed, available = _memory_check(facts)
        assert needed == 4 + BUILD_OVERHEAD_GB and round(available, 2) == 7.66
        assert needed > available
        assert _container_memory(facts) == f"{4 + BUILD_OVERHEAD_GB:g}g"
        # Without the build's own heap setting there is nothing to check against.
        assert _memory_check(SparkRuntimeFacts(spark_submit="bin/spark-submit")) == (None, None)
