EVENT_LOG = Path(__file__).parent / "fixtures/spark/real_event_log.jsonl"


class FakeEnvironment:
    """Records what it was asked to do; replays a real event log for spark-submit."""

    kind = "fake"

    def __init__(self, tmp: Path, *, stdout: str = "", exit_code: int = 0, write_log: bool = True):
        self.host_workdir = tmp
        self.container_workdir = "/work"
        self.files: dict[str, bytes] = {}
        self.commands: list[tuple[str, dict]] = []
        self.started_with: str | None = None
        self.stopped = False
        self._stdout = stdout
        self._exit = exit_code
        self._write_log = write_log

    async def start(self, image: str, **_: object) -> None:
        self.started_with = image

    async def put_files(self, files: dict[str, bytes]) -> None:
        self.files.update(files)

    async def run(self, command: str, *, timeout=None, cwd=None, env=None) -> CommandResult:
        self.commands.append((command, dict(env or {})))
        if "spark-submit" in command and self._write_log:
            events = self.host_workdir / "events"
            events.mkdir(parents=True, exist_ok=True)
            shutil.copy(EVENT_LOG, events / "local-1700000000000")
        return CommandResult(exit_code=self._exit, stdout=self._stdout, stderr="")

    async def stop(self) -> None:
        self.stopped = True


def printed(**payload) -> str:
    lines = []
    if "result" in payload:
        lines.append(f"{RESULT} {json.dumps(payload['result'])}")
    if "plan" in payload:
        lines.append(f"{PLAN} {json.dumps(payload['plan'])}")
    if "failed" in payload:
        lines.append(f"{FAILED} {json.dumps(payload['failed'])}")
    if payload.get("ok", True) and "failed" not in payload:
        lines.append(f"{SUCCESS} 3.5.1")
    return "\n".join(lines) + "\n"


class TestTheDriver:
    def test_the_learners_code_runs_inside_a_disclosed_driver(self) -> None:
        driver = render_driver('result = df.groupBy("country").count()')
        assert "Generated by RepoLab" in driver
        assert "'result = df.groupBy(\"country\").count()'" in driver
        assert "/work/sales.csv" in driver

    def test_output_markers_are_decoded(self) -> None:
        out = printed(result={"columns": ["a"], "rows": [[1]]}, plan="Exchange")
        found = parse_output(out)
        assert found[RESULT] == {"columns": ["a"], "rows": [[1]]}
        assert found[PLAN] == "Exchange" and found[SUCCESS] == "3.5.1"

    def test_the_dataset_is_deterministic_and_described(self) -> None:
        a, spec = sample_dataset()
        b, _ = sample_dataset()
        assert a == b and spec.rows == 2000 and len(spec.preview) == 8
        assert spec.columns[0] == ("order_id", "INT")

    def test_partitions_reach_spark_and_adaptive_execution_is_off(self) -> None:
        args = " ".join(SnippetConfig(shuffle_partitions=8).submit_args())
        assert "spark.sql.shuffle.partitions=8" in args
        assert "spark.sql.adaptive.enabled=false" in args
        assert "spark.eventLog.enabled=true" in args


class TestARun:
    def run(self, tmp_path: Path, **env_kw):
        environment = FakeEnvironment(tmp_path / "work", **env_kw)
        result = asyncio.run(
            SnippetRunner(environment, runs_root=tmp_path / "runs").run(
                image="spark:test", code="result = df", spark_submit="/opt/spark/bin/spark-submit"
            )
        )
        return result, environment

    def test_measurements_come_from_the_event_log(self, tmp_path: Path) -> None:
        result, environment = self.run(
            tmp_path,
            stdout=printed(
                result={"columns": ["c"], "rows": [["US"]]},
                plan="*(2) HashAggregate\n+- Exchange x",
            ),
        )
        assert result.ok and result.columns == ["c"]
        assert result.measurements is not None and result.measurements.stage_count > 0
        assert result.event_log_sha256 and len(result.event_log_sha256) == 64
        assert environment.stopped
        # Without a network, Spark is told to bind to loopback.
        assert environment.commands[-1][1]["SPARK_LOCAL_IP"] == "127.0.0.1"

    def test_a_failing_snippet_carries_the_error_and_no_invented_numbers(
        self, tmp_path: Path
    ) -> None:
        result, _ = self.run(
            tmp_path,
            stdout=printed(failed="AnalysisException: cannot resolve 'cuntry'"),
            exit_code=4,
            write_log=False,
        )
        assert not result.ok
        assert "cannot resolve" in (result.error or "")
        assert result.measurements is None and result.jobs == 0

    def test_a_zero_exit_is_not_success_without_the_marker(self, tmp_path: Path) -> None:
        result, _ = self.run(tmp_path, stdout="", write_log=False)
        assert not result.ok


